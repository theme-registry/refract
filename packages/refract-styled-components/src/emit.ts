/**
 * The styled-components `emit()` module assembler (§8) — writes **TS/JS modules**, not a stylesheet.
 *
 * What lands on disk (self-contained — a downstream app imports these and drops refract at runtime):
 *  - **theme.ts** — the literal theme object (`export const theme = { … } as const`) + the flat, tree-
 *    shakeable `css` recipe consts + a grouped `recipes` barrel + (if the raw defines `globals`) a
 *    `GlobalStyle`. `emit: "split"` peels the recipes into `recipes.ts` and the `GlobalStyle` into
 *    `global.ts`.
 *  - **media.ts** (always) / **scheme.ts** (iff modes ride `prefers-color-scheme`) — vendored tagged
 *    templates with this theme's concrete `@media` strings baked in.
 *  - **theme.d.ts** (iff `language: "ts"`) — augments styled-components' `DefaultTheme` from `typeof theme`.
 *  - **color-math.ts** is materialized by the shared build plumbing (`emitTheme` + `VENDOR_HELPERS`),
 *    not here — this module only wires the `import`.
 */
import type { EmitOutput } from "@theme-registry/refract";
import type { MediaDescriptor, MediaVariant } from "@theme-registry/refract";

const VARIANTS: ReadonlyArray<MediaVariant> = ["min", "max", "exact"];

/** color-math exports surfaced on `theme` when `helpers: ["color-math"]` is opted in. */
export const COLOR_MATH_ATTACH: ReadonlyArray<string> = ["lighten", "darken", "alpha"];

/**
 * Generate a self-contained SC media-helper module (source text) for `breakpoints`, reading the
 * concrete `@media` query strings from the already-built core {@link MediaDescriptor}.
 */
export const vendorMediaHelper = <TBreakpoint extends string>(
  breakpoints: Record<TBreakpoint, number>,
  media: MediaDescriptor<TBreakpoint>,
): string => {
  const keys = (Object.keys(breakpoints) as TBreakpoint[]).sort(
    (a, b) => breakpoints[a] - breakpoints[b],
  );

  const groups = keys
    .map(key => {
      const group = media[key];
      const variants = VARIANTS.map(
        variant => `    ${variant}: wrap(${JSON.stringify(group?.[variant] ?? "")}),`,
      ).join("\n");
      return `  ${JSON.stringify(key)}: {\n${variants}\n  },`;
    })
    .join("\n");

  return `// Vendored, self-contained styled-components media helper (generated by @theme-registry/refract).
// Only dependency: styled-components. Concrete @media strings are baked in for this theme's breakpoints.
import { css } from "styled-components";

const wrap = (query) => {
  const fn = query
    ? (styles, ...interpolations) => css\`\${query} { \${css(styles, ...interpolations)} }\`
    : (styles, ...interpolations) => css\`\${css(styles, ...interpolations)}\`;
  fn.query = query;
  return fn;
};

export const media = {
${groups}
};

export default media;
`;
};

